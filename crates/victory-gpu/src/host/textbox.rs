//! Simple top-left bitmap text box drawn onto the swap chain back buffer.

use std::sync::atomic::{AtomicBool, Ordering};

use windows::Win32::Graphics::Direct3D12::*;
use windows::Win32::Graphics::Dxgi::Common::*;
use windows_sys::Win32::UI::Input::KeyboardAndMouse::GetAsyncKeyState;
use windows_sys::Win32::UI::WindowsAndMessaging::{GetForegroundWindow, GetWindowThreadProcessId};

use super::{Host, HostList, transition};

/// A character's dots, and with the space beside and below it.
pub(super) const GLYPH: (u32, u32) = (5, 7);
pub(super) const CELL: (u32, u32) = (6, 9);
pub(super) const RIM: u32 = 3;

/// The texts are put into one of these in turn: the card reads the others,
/// at most a couple of updates old.
const UPLOADS: usize = 4;

/// Returns true once per key-down edge of `vk` while one of our windows has focus.
pub(super) fn key_pressed(vk: u16, was_down: &AtomicBool) -> bool {
    // SAFETY: a plain query.
    let down = unsafe { GetAsyncKeyState(i32::from(vk)) } < 0;
    if was_down.swap(down, Ordering::Relaxed) || !down {
        return false;
    }
    let mut process = 0;
    // SAFETY: plain queries; room for the answer.
    unsafe { GetWindowThreadProcessId(GetForegroundWindow(), &mut process) };
    process == std::process::id()
}

